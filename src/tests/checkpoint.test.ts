test('恢复事实在预算内保留完整状态文件路径，不渲染积压总数',t=>{
  const f=fixture(t),session='s'.repeat(256);f.store.updatePeer(f.x.id,{sessionId:session});f.store.updatePeer(f.c.id,{name:'\u0000'.repeat(128)});
  const pair=f.store.pair(f.c.id,f.x.id),actor={host:'codex' as const,sessionId:session,callId:'bounded-facts'};
  const directory=tmpdir(),file=path.join(directory,'"'.repeat(1024-Buffer.byteLength(directory)-1));
  f.broker.recovery.checkpoint(actor,{action:'set',path:file});
  for(let index=0;index<8;index++){
    f.store.accept(pair,f.x,'另一段私密正文','out-'+index);
    const incoming=f.store.accept(pair,f.c,'不允许进入恢复包的正文','in-'+index);f.store.transition(incoming.id,'contextObserved');
  }
  const facts=f.broker.recovery.facts(actor)!;assert.ok(facts);assert.ok(Buffer.byteLength(facts.text)<=4096);assert.ok(facts.text.includes(JSON.stringify(file)));assert.doesNotMatch(facts.text,/\(\+\d+\)|私密正文|不允许进入/);
  assert.equal(f.store.messages().length,16);assert.ok(f.store.messages().every(message=>message.attempts===0));
  const longSession='会话'.repeat(1500);f.store.updatePeer(f.x.id,{sessionId:longSession});
  const bounded=f.broker.recovery.facts({...actor,sessionId:longSession})!;assert.ok(Buffer.byteLength(bounded.text)<=4096);assert.match(bounded.text,/truncated; use checkpoint get\/status/);assert.doesNotMatch(bounded.text,/\uFFFD/);
});

for(const host of ['codex','claude'] as const)test(`${host} 恢复提示只列上次发信后的三条已观察消息，不按措辞或闲置时间丢弃`,t=>{
  t.mock.timers.enable({apis:['Date'],now:1000});
  const f=fixture(t),pair=f.store.pair(f.c.id,f.x.id),self=host==='codex'?f.x:f.c,partner=host==='codex'?f.c:f.x,binding=f.store.bindings.current(self.id),actor={host,memberId:self.id,sessionId:self.sessionId!,callId:'frontier',...(binding?{binding:{key:binding.key,epoch:binding.epoch}}:{})};
  for(let index=0;index<40;index++){
    const old=f.store.accept(pair,partner,'历史知会，无需回复','old-'+index);f.store.transition(old.id,'contextObserved');
  }
                                  
  const ack=f.store.accept(pair,self,'已知悉，继续实施','ack');
  assert.match(f.broker.recovery.facts(actor)!.text,/partner msgs since your last send \(<=3, newest first\): none;/);
  const recent=['请继续','FYI：附加信息','措辞不同的跟进','最新纠正'].map((body,index)=>{
    const message=f.store.accept(pair,partner,body,'recent-'+index);f.store.transition(message.id,'contextObserved');return message.id;
  });
  const responded=f.store.accept(pair,partner,'已经处理的消息','responded');f.store.transition(responded.id,'responded');
  for(const state of ['accepted','runtimeQueued','held','unknown','refused','expired'] as const){
    const message=f.store.accept(pair,partner,'尚无入上下文证据','state-'+state);if(state!=='accepted')f.store.transition(message.id,state);
  }
  t.mock.timers.tick(365*24*60*60*1000);
  const text=f.broker.recovery.facts(actor)!.text,field=text.split('partner msgs since your last send (<=3, newest first): ')[1]!.split(';')[0]!;
  assert.deepEqual(JSON.parse('['+field+']'),recent.slice(-3).reverse());
  assert.ok(!text.includes(ack.id)&&!text.includes(responded.id));assert.doesNotMatch(text,/\(\+\d+\)|your msgs w\/o|历史知会|措辞不同/);
  assert.equal(f.store.messages(100).filter(message=>message.state==='contextObserved').length,44);
  const reply=f.store.accept(pair,self,'关联最新消息','reply',recent.at(-1));
  assert.equal(f.store.message(recent.at(-1)!).state,'responded');
  assert.match(f.broker.recovery.facts(actor)!.text,/newest first\): none;/);assert.equal(f.store.message(reply.id).attempts,0);
});

