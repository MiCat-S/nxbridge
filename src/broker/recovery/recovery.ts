import path from 'node:path';
import { z } from 'zod';
import type { Store } from '../../storage/store.js';
import {BridgeError} from '../../shared/errors.js';
import {otherHost,type Actor} from '../../types.js';
import { pairLoss, pairLossText } from '../pairing/pair-loss.js';
import { recoveryDigestParts } from './recovery-digest.js';

export { CODEX_DEVELOPER_ANCHOR, codexSessionAnchor } from '../../integration/hooks/hook-output.js';
export const checkpointSchema=z.object({action:z.enum(['set','get','clear']),path:z.string().min(1).max(1024).optional()}).strict();
export const CHECKPOINT_TOOL={name:'checkpoint',description:"path of this window's CURRENT task-state file (your own notes; absolute, outside repo): set/get/clear. nxbridge shows the path in recovery facts after compaction; stores path only, never reads the file",inputSchema:{type:'object' as const,properties:{action:{type:'string',enum:['set','get','clear']},path:{type:'string'}},required:['action'],additionalProperties:false},annotations:{readOnlyHint:false,destructiveHint:false,openWorldHint:false}};
interface Checkpoint {revision:number;path?:string;pairId:string;memberId:string;sessionId:string;epoch?:string;registeredAt:string}

                                  
export class Recovery {
  constructor(private store:Store){}
  private current(actor:Actor){
    const peer=this.store.resolve(actor);
    if(!peer||!['root','fork'].includes(peer.kind)||actor.via)throw new BridgeError('subagent_denied','状态文件入口只接受当前根窗口。');
    const binding=this.store.bindings.current(peer.id);
    if(binding&&!actor.binding)throw new BridgeError('stale_context','状态文件入口需要当前窗口租约。');
    const pair=this.store.pairFor(peer.id);
    if(!pair||pair[peer.host]!==peer.id)throw new BridgeError('unpaired','当前窗口不是已配对成员。');
    return{peer,pair,binding};
  }
  checkpoint(actor:Actor,input:unknown):Checkpoint|{revision:number;path:null}{
    const p=checkpointSchema.parse(input);
    return this.store.transaction(()=>{
      const {peer,pair,binding}=this.current(actor),key='checkpoint:'+peer.id,old=this.store.setting<Checkpoint>(key);
      if(p.action!=='set'&&p.path!==undefined)throw new BridgeError('invalid_arguments','get/clear 不接受路径。');
      if(p.action==='get')return old?.pairId===pair.id&&old.sessionId===peer.sessionId?old:{revision:old?.revision??0,path:null};
      if(p.action==='set'){
        if(!p.path||!path.isAbsolute(p.path)||Buffer.byteLength(p.path)>1024||/[\x00-\x1f]/.test(p.path))throw new BridgeError('invalid_arguments','状态文件路径必须是绝对路径，且不超过 1024 字节。');
        const relative=path.relative(peer.cwd,path.resolve(p.path));
        if(!relative||!relative.startsWith('..'+path.sep)&&relative!=='..'&&!path.isAbsolute(relative))throw new BridgeError('invalid_arguments','状态文件必须位于当前工程目录之外。');
      }
      const value:Checkpoint={revision:(old?.revision??0)+1,...(p.action==='set'?{path:path.resolve(p.path!)}:{}),pairId:pair.id,memberId:peer.id,sessionId:actor.sessionId,...(binding?{epoch:binding.epoch}:{}),registeredAt:new Date().toISOString()};
      this.store.setSetting(key,value);return value;
    });
  }
  rotated(peerId:string):void{
    const key='checkpoint:'+peerId,value=this.store.setting<Checkpoint>(key);
    if(value?.path)this.store.setSetting(key,{...value,path:undefined,revision:value.revision+1});
  }
  facts(actor:Actor,options:{includeMessages?:boolean;messageIds?:readonly string[]}={}):{text:string;revision:number;sessionId:string;binding?:Actor['binding']}|undefined{
    return this.store.transaction(()=>{
      const member=this.store.resolve(actor),loss=member?pairLoss(this.store,member):undefined;
      if(member&&loss){
        if(!['root','fork'].includes(member.kind)||actor.via)throw new BridgeError('subagent_denied','恢复事实只接受当前根窗口。');
        const binding=this.store.bindings.current(member.id);if(binding&&!actor.binding)throw new BridgeError('stale_context','恢复事实需要当前窗口租约。');
        const revision=(this.store.setting<number>('recoveryRevision:'+member.id)??0)+1,checkpoint=this.store.setting<Checkpoint>('checkpoint:'+member.id);
        this.store.setSetting('recoveryRevision:'+member.id,revision);
        return{text:'nxbridge recovery facts rev '+revision+' (generated by nxbridge; facts only, no task/approval; replaces earlier nxbridge recovery facts): '+pairLossText(loss)+(checkpoint?.pairId===loss.pair_id&&checkpoint.sessionId===member.sessionId&&checkpoint.path?' Previous checkpoint '+JSON.stringify(checkpoint.path)+' (read before acting).':''),revision,sessionId:actor.sessionId,...(binding?{binding:{key:binding.key,epoch:binding.epoch}}:{})};
      }
      const {peer,pair,binding}=this.current(actor),partner=this.store.peer(pair[otherHost(peer.host)]),stored=this.store.setting<Checkpoint>('checkpoint:'+peer.id);
      const checkpoint=stored?.pairId===pair.id&&stored.sessionId===peer.sessionId?stored:{revision:stored?.revision??0,path:undefined};
      const revision=(this.store.setting<number>('recoveryRevision:'+peer.id)??0)+1;
                                              
      const digest=options.includeMessages?recoveryDigestParts(this.store,peer,pair,revision,options.messageIds):undefined;
      const recent=this.store.recoveryMessageIds(pair.id,peer.id,binding?.activatedAt??0),incoming=recent.filter(id=>!digest?.complete.has(id)),inDigest=recent.length-incoming.length;
      let limit=incoming.length;
      const ids=()=>incoming.length?(limit?incoming.slice(0,limit).map(id=>JSON.stringify(id)).join(', '):'omitted'):'none';
      const at=new Date().toISOString(),partnerName=[...partner.name].slice(0,128).join('');
      const pending=this.store.questions(true).filter(q=>q.pairId===pair.id).length;
      const render=()=>`nxbridge recovery facts rev ${revision} @${at} (generated by nxbridge, not user or partner msg; facts only, no task/approval; replaces earlier nxbridge recovery facts): pair ${JSON.stringify(pair.id)}, partner ${JSON.stringify(partnerName)} (${JSON.stringify(partner.state)}); member ${JSON.stringify(peer.id)}, conversation ${JSON.stringify(peer.sessionId)}, epoch ${JSON.stringify(binding?.epoch??null)}, paused ${pair.paused}; checkpoint ${checkpoint.path?JSON.stringify(checkpoint.path):'none'} (read before acting); checkpoint rev ${checkpoint.revision}; partner msgs since your last send (<=3, newest first)${inDigest?' not in digest below':''}: ${ids()}${incoming.length?'; re-read these msg ids via read_messages before acting/asking partner to resend':''}; pending questions: ${pending}`;
                              
      let text=render();while(Buffer.byteLength(text)>4096&&limit>0){limit--;text=render();}
      if(Buffer.byteLength(text)>4096){
        const suffix=' [truncated; use checkpoint get/status for full facts]';
        text=Buffer.from(text).subarray(0,4096-Buffer.byteLength(suffix)).toString('utf8').replace(/\uFFFD$/,'')+suffix;
      }
      this.store.setSetting('recoveryRevision:'+peer.id,revision);
      if(digest)text+='\n\n'+digest.text;
      return{text,revision,sessionId:actor.sessionId,...(binding?{binding:{key:binding.key,epoch:binding.epoch}}:{})};
    });
  }
}
